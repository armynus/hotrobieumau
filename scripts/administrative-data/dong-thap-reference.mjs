export function expandRef(spec) {
 const [identity, scope = 'whole'] = spec.split('|');
 const [typedName, district = null] = identity.split('@');
 const match = typedName.match(/^([xpt]):(.*)$/u);
 const type = match?.[1] ?? 'x';
 const name = ({x:'Xã',p:'Phường',t:'Thị trấn'})[type] + ' ' + (match?.[2] ?? typedName);
 return {name, district, scope};
}
